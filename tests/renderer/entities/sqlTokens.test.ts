import { describe, expect, it } from 'vitest'
import { darkTheme } from '@renderer/shared/theme'
import { sqlTokenCss, tokenizeSql } from '@renderer/entities/sql-lang'

function tokenOf(pieces: readonly { text: string; token: string | null }[], text: string) {
  return pieces.find((p) => p.text === text)?.token ?? null
}

describe('tokenizeSql', () => {
  it('키워드·타입·문자열을 각각 다른 토큰으로 나눈다', () => {
    const pieces = tokenizeSql('postgres', `CREATE TABLE t ("id" bigint DEFAULT 'x')`)
    expect(tokenOf(pieces, 'CREATE')).toBe('keyword')
    expect(tokenOf(pieces, 'TABLE')).toBe('keyword')
    expect(tokenOf(pieces, 'bigint')).toBe('type')
    expect(tokenOf(pieces, "'x'")).toBe('string')
  })

  it('인용 식별자를 문자열과 다른 토큰으로 준다', () => {
    // 이게 이 작업의 핵심이다. 문법은 둘을 구분하는데(quoted identifier는
    // special(string)) 기존 스타일이 한 색으로 묶어 버렸다. DDL 미리보기는
    // 모든 식별자를 인용하므로 그대로 두면 화면이 거의 한 색이 된다.
    const pieces = tokenizeSql('postgres', `SELECT "col" FROM t WHERE x = 'lit'`)
    expect(tokenOf(pieces, '"col"')).toBe('ident')
    expect(tokenOf(pieces, "'lit'")).toBe('string')
  })

  it('mysql 백틱 식별자도 ident로 준다', () => {
    const pieces = tokenizeSql('mysql', 'SELECT `col` FROM t')
    expect(tokenOf(pieces, '`col`')).toBe('ident')
  })

  it('자동 증가 키워드를 방언별로 알아본다', () => {
    expect(
      tokenOf(tokenizeSql('postgres', 'x bigint GENERATED BY DEFAULT AS IDENTITY'), 'IDENTITY'),
    ).toBe('keyword')
    expect(tokenOf(tokenizeSql('mysql', 'x bigint AUTO_INCREMENT'), 'AUTO_INCREMENT')).toBe(
      'keyword',
    )
    expect(tokenOf(tokenizeSql('sqlite', 'PRIMARY KEY("id" AUTOINCREMENT)'), 'AUTOINCREMENT')).toBe(
      'keyword',
    )
  })

  it('줄바꿈을 조각으로 보존한다', () => {
    const pieces = tokenizeSql('postgres', 'SELECT 1\nFROM t')
    expect(pieces.map((p) => p.text).join('')).toBe('SELECT 1\nFROM t')
  })

  it('SQL이 아닌 엔진도 표준 SQL로 토큰화한다', () => {
    expect(tokenOf(tokenizeSql(undefined, 'SELECT 1'), 'SELECT')).toBe('keyword')
  })
})

describe('sqlTokenCss', () => {
  it('모든 토큰에 테마 색을 낸다', () => {
    const css = sqlTokenCss(darkTheme)
    for (const token of [
      'keyword',
      'fn',
      'ident',
      'string',
      'number',
      'type',
      'comment',
      'punct',
    ]) {
      expect(css).toContain(`.tok-${token}`)
    }
    expect(css).toContain(darkTheme.syntax.ident)
    // 색만이 아니라 서식도 함께 낸다 — 편집기와 같은 모양이어야 한다.
    expect(css).toContain('font-weight: 600')
    expect(css).toContain('font-style: italic')
  })
})
