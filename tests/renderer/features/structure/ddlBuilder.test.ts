import { describe, expect, it } from 'vitest'
import {
  buildAddForeignKey,
  buildCreateIndex,
  buildCreateTable,
  quoteIdent,
  supportsAddForeignKey,
  TYPE_SUGGESTIONS,
  validateCreateTable,
  validateForeignKey,
  validateIndex,
} from '../../../../src/renderer/features/structure/model/ddlBuilder'
import { SQL_ENGINE_IDS } from '../../../../src/shared/types/connection'

describe('quoteIdent', () => {
  it('postgres/sqlite는 큰따옴표, mysql/mariadb는 백틱', () => {
    expect(quoteIdent('postgres', 'users')).toBe('"users"')
    expect(quoteIdent('sqlite', 'users')).toBe('"users"')
    expect(quoteIdent('mysql', 'users')).toBe('`users`')
    expect(quoteIdent('mariadb', 'users')).toBe('`users`')
  })

  it('내부 인용 문자를 두 번 적어 식별자 경계 탈출을 막는다', () => {
    expect(quoteIdent('postgres', 'we"ird')).toBe('"we""ird"')
    expect(quoteIdent('mysql', 'we`ird')).toBe('`we``ird`')
    // 교차 인용 문자는 그대로 둔다 — 해당 방언에서 특수문자가 아니다.
    expect(quoteIdent('postgres', 'back`tick')).toBe('"back`tick"')
  })
})

describe('buildCreateTable', () => {
  it('컬럼·NOT NULL·DEFAULT·복합 PK를 담은 CREATE TABLE을 만든다', () => {
    const sql = buildCreateTable('postgres', {
      schema: 'public',
      table: 'orders',
      columns: [
        { name: 'id', type: 'bigserial', notNull: true, primaryKey: true, autoIncrement: false },
        { name: 'tenant', type: 'text', notNull: true, primaryKey: true, autoIncrement: false },
        { name: 'status', type: 'text', notNull: false, primaryKey: false, defaultExpr: "'draft'", autoIncrement: false },
      ],
    })
    expect(sql).toBe(
      'CREATE TABLE "public"."orders" (\n' +
        '  "id" bigserial NOT NULL,\n' +
        '  "tenant" text NOT NULL,\n' +
        '  "status" text DEFAULT \'draft\',\n' +
        '  PRIMARY KEY ("id", "tenant")\n' +
        ')',
    )
  })

  it('PK 컬럼이 없으면 PRIMARY KEY 절을 생략한다', () => {
    const sql = buildCreateTable('sqlite', {
      table: 'logs',
      columns: [{ name: 'line', type: 'text', notNull: false, primaryKey: false, autoIncrement: false }],
    })
    expect(sql).toBe('CREATE TABLE "logs" (\n  "line" text\n)')
  })

  it('스키마가 비면 테이블명만 한정한다', () => {
    const sql = buildCreateTable('mysql', {
      schema: '',
      table: 'items',
      columns: [{ name: 'id', type: 'bigint', notNull: true, primaryKey: true, autoIncrement: false }],
    })
    expect(sql).toBe('CREATE TABLE `items` (\n  `id` bigint NOT NULL,\n  PRIMARY KEY (`id`)\n)')
  })

  it('빈 defaultExpr는 DEFAULT 절을 만들지 않는다', () => {
    const sql = buildCreateTable('postgres', {
      table: 't',
      columns: [{ name: 'a', type: 'text', notNull: false, primaryKey: false, defaultExpr: '  ', autoIncrement: false }],
    })
    expect(sql).not.toContain('DEFAULT')
  })

  it('postgres 자동 증가는 표준 IDENTITY 절을 붙인다', () => {
    const sql = buildCreateTable('postgres', {
      schema: 'public',
      table: 'users',
      columns: [
        { name: 'id', type: 'bigint', notNull: false, primaryKey: true, autoIncrement: true },
        { name: 'email', type: 'text', notNull: true, primaryKey: false, autoIncrement: false },
      ],
    })
    expect(sql).toBe(
      'CREATE TABLE "public"."users" (\n' +
        '  "id" bigint GENERATED BY DEFAULT AS IDENTITY,\n' +
        '  "email" text NOT NULL,\n' +
        '  PRIMARY KEY ("id")\n' +
        ')',
    )
  })

  it('mysql/mariadb 자동 증가는 AUTO_INCREMENT를 붙인다', () => {
    for (const dialect of ['mysql', 'mariadb'] as const) {
      const sql = buildCreateTable(dialect, {
        table: 'users',
        columns: [{ name: 'id', type: 'bigint', notNull: false, primaryKey: true, autoIncrement: true }],
      })
      expect(sql).toBe(
        'CREATE TABLE `users` (\n  `id` bigint AUTO_INCREMENT,\n  PRIMARY KEY (`id`)\n)',
      )
    }
  })

  it('sqlite 자동 증가는 컬럼이 아니라 PK 절에 AUTOINCREMENT를 넣는다', () => {
    // sqlite 문법은 AUTOINCREMENT를 PK 절 안에서만 받는다. 컬럼 절에 붙이는
    // 형태는 인라인 PK가 아니면 성립하지 않는다(설계 §2.1 실측).
    const sql = buildCreateTable('sqlite', {
      table: 'users',
      columns: [
        { name: 'id', type: 'integer', notNull: false, primaryKey: true, autoIncrement: true },
        { name: 'label', type: 'text', notNull: false, primaryKey: false, autoIncrement: false },
      ],
    })
    expect(sql).toBe(
      'CREATE TABLE "users" (\n' +
        '  "id" integer,\n' +
        '  "label" text,\n' +
        '  PRIMARY KEY ("id" AUTOINCREMENT)\n' +
        ')',
    )
  })

  it('sqlite 복합 PK에는 AUTOINCREMENT를 넣지 않는다', () => {
    // 문법 오류가 되는 형태다. 검증이 이 조합을 먼저 막지만(Task 2), 빌더도
    // 깨진 SQL을 만들어 내지는 않는다.
    const sql = buildCreateTable('sqlite', {
      table: 't',
      columns: [
        { name: 'a', type: 'integer', notNull: false, primaryKey: true, autoIncrement: true },
        { name: 'b', type: 'text', notNull: false, primaryKey: true, autoIncrement: false },
      ],
    })
    expect(sql).toContain('PRIMARY KEY ("a", "b")')
    expect(sql).not.toContain('AUTOINCREMENT')
  })

  it('DEFAULT·NOT NULL과 함께 쓰면 자동 증가 절이 마지막에 온다', () => {
    // pg는 절 순서를 가리지 않는 것을 확인했다(설계 §2.2). 사람이 읽기 좋은
    // 순서로 고정해 둔다.
    const sql = buildCreateTable('postgres', {
      table: 't',
      columns: [
        {
          name: 'id',
          type: 'bigint',
          notNull: true,
          primaryKey: false,
          defaultExpr: '0',
          autoIncrement: true,
        },
      ],
    })
    expect(sql).toBe(
      'CREATE TABLE "t" (\n' +
        '  "id" bigint DEFAULT 0 NOT NULL GENERATED BY DEFAULT AS IDENTITY\n' +
        ')',
    )
  })

  it('자동 증가를 끄면 아무 절도 붙지 않는다', () => {
    const sql = buildCreateTable('postgres', {
      table: 't',
      columns: [{ name: 'id', type: 'bigint', notNull: false, primaryKey: true, autoIncrement: false }],
    })
    expect(sql).not.toContain('IDENTITY')
    expect(sql).not.toContain('AUTO_INCREMENT')
  })
})

describe('buildAddForeignKey', () => {
  it('제약 이름·ON DELETE를 담은 ALTER TABLE을 만든다', () => {
    const sql = buildAddForeignKey('postgres', {
      schema: 'public',
      table: 'orders',
      constraintName: 'fk_orders_user',
      columns: ['user_id'],
      refSchema: 'public',
      refTable: 'users',
      refColumns: ['id'],
      onDelete: 'CASCADE',
    })
    expect(sql).toBe(
      'ALTER TABLE "public"."orders"\n' +
        '  ADD CONSTRAINT "fk_orders_user" FOREIGN KEY ("user_id")\n' +
        '  REFERENCES "public"."users" ("id")\n' +
        '  ON DELETE CASCADE',
    )
  })

  it('제약 이름이 비면 CONSTRAINT 절을, NO ACTION이면 ON DELETE 절을 생략한다', () => {
    const sql = buildAddForeignKey('mysql', {
      table: 'orders',
      columns: ['user_id'],
      refTable: 'users',
      refColumns: ['id'],
      onDelete: 'NO ACTION',
    })
    expect(sql).toBe(
      'ALTER TABLE `orders`\n  ADD FOREIGN KEY (`user_id`)\n  REFERENCES `users` (`id`)',
    )
  })

  it('sqlite는 지원하지 않는다 — capability 함수와 빌더가 함께 막는다', () => {
    expect(supportsAddForeignKey('sqlite')).toBe(false)
    expect(supportsAddForeignKey('postgres')).toBe(true)
    expect(() =>
      buildAddForeignKey('sqlite', { table: 't', columns: ['a'], refTable: 'r', refColumns: ['b'] }),
    ).toThrow(/sqlite/)
  })
})

describe('buildCreateIndex', () => {
  it('UNIQUE·복합 컬럼 인덱스를 만들고 인덱스명은 한정하지 않는다', () => {
    const sql = buildCreateIndex('postgres', {
      schema: 'public',
      table: 'orders',
      indexName: 'idx_orders_user',
      columns: ['user_id', 'created_at'],
      unique: true,
    })
    expect(sql).toBe(
      'CREATE UNIQUE INDEX "idx_orders_user" ON "public"."orders" ("user_id", "created_at")',
    )
  })

  it('unique=false면 UNIQUE를 생략한다', () => {
    const sql = buildCreateIndex('mariadb', {
      table: 't',
      indexName: 'i',
      columns: ['c'],
      unique: false,
    })
    expect(sql).toBe('CREATE INDEX `i` ON `t` (`c`)')
  })
})

