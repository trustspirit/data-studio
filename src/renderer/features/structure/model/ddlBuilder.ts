export type DdlIssue = string

/**
 * pg가 IDENTITY를 허용하는 타입.
 *
 * 서버 오류 메시지는 `smallint, integer, or bigint`만 말하지만 실제로는 내부
 * 별칭도 받는다 — `int8`·`int4`·`int`·`int2`를 실측으로 확인했다. 메시지를
 * 그대로 옮겨 적으면 엔진이 받아 주는 입력을 UI가 막는다.
 */
const PG_IDENTITY_TYPES: ReadonlySet<string> = new Set([
  'smallint', 'integer', 'bigint', 'int', 'int2', 'int4', 'int8',
])

/**
 * `serial` 계열. 그 자체가 시퀀스 DEFAULT를 만들므로 IDENTITY와 겹쳐
 * pg가 거부한다(`both default and identity specified`). 이 타입들은
 * `TYPE_SUGGESTIONS`에 있어서 사용자가 고르기 쉽다 — 안내가 필요한 조합이다.
 */
const PG_SERIAL_TYPES: ReadonlySet<string> = new Set([
  'serial', 'bigserial', 'smallserial', 'serial2', 'serial4', 'serial8',
])

function normalizedType(raw: string): string {
  return raw.trim().toLowerCase()
}

/**
 * 자동 증가 관련 검증. 규칙이 방언마다 다르고 근거가 전부 실측이다 —
 * 설계 문서 §2에 어떤 DDL이 어떤 이유로 거부되었는지 적혀 있다.
 *
 * 규칙을 엔진의 실제 제약보다 좁게 잡지 않는다. 엔진이 받아 주는 것을 UI가
 * 막으면 사용자는 왜 안 되는지 알 방법이 없다. 그래서 pg에는 "하나만"·"PK여야"
 * 규칙을 걸지 않는다 — pg는 둘 다 허용한다.
 */
function autoIncrementIssues(
  dialect: SqlEngineId,
  spec: CreateTableSpec,
): readonly DdlIssue[] {
  const autos = spec.columns.filter((c) => c.autoIncrement)
  if (autos.length === 0) return []

  const issues: DdlIssue[] = []
  const pkCount = spec.columns.filter((c) => c.primaryKey).length

  for (const c of autos) {
    const name = c.name.trim()
    const label = name === '' ? '자동 증가 컬럼' : `'${name}'`
    const type = normalizedType(c.type)

    if (c.defaultExpr !== undefined && c.defaultExpr.trim() !== '')
      issues.push(`${label}은 자동 증가이므로 DEFAULT를 함께 지정할 수 없습니다.`)

    if (dialect === 'postgres') {
      if (PG_SERIAL_TYPES.has(type))
        issues.push(
          `${label}의 ${type}은 그 자체가 자동 증가입니다. 타입을 bigint로 바꾸거나 자동 증가를 끄세요.`,
        )
      else if (type !== '' && !PG_IDENTITY_TYPES.has(type))
        issues.push(`${label}은 정수 타입(smallint·integer·bigint)이어야 자동 증가가 됩니다.`)
    }

    if (dialect === 'sqlite') {
      if (type !== '' && type !== 'integer')
        issues.push(
          `${label}의 타입은 정확히 integer여야 합니다. int·bigint는 id가 비어 저장되고 오류도 나지 않습니다.`,
        )
      if (!c.primaryKey) issues.push(`${label}은 자동 증가이므로 PK여야 합니다.`)
      if (pkCount > 1) issues.push('sqlite는 복합 PK에 자동 증가를 쓸 수 없습니다.')
    }

    if ((dialect === 'mysql' || dialect === 'mariadb') && !c.primaryKey)
      issues.push(`${label}은 자동 증가이므로 PK여야 합니다.`)
  }

  // pg는 IDENTITY 컬럼을 여러 개 허용한다(실측). mysql·sqlite는 하나뿐이다.
  if (dialect !== 'postgres' && autos.length > 1)
    issues.push('자동 증가 컬럼은 테이블에 하나만 둘 수 있습니다.')

  // 같은 위반이 컬럼마다 반복될 수 있다(복합 PK 규칙 등). 중복은 걷어낸다.
  return [...new Set(issues)]
}

/** 폼 검증. 빌더는 총함수로 두고(주어진 대로 인용), 실행 가능 여부는 여기서 판정한다. */
export function validateCreateTable(
  dialect: SqlEngineId,
  spec: CreateTableSpec,
): readonly DdlIssue[] {
  const issues: DdlIssue[] = []
  if (spec.table.trim() === '') issues.push('테이블 이름을 입력하세요.')
  if (spec.columns.length === 0) issues.push('컬럼을 하나 이상 추가하세요.')
  spec.columns.forEach((c, i) => {
    if (c.name.trim() === '') issues.push(`${i + 1}번째 컬럼 이름이 비어 있습니다.`)
    if (c.type.trim() === '') issues.push(`${i + 1}번째 컬럼 타입이 비어 있습니다.`)
  })
  const names = spec.columns.map((c) => c.name.trim()).filter((n) => n !== '')
  if (new Set(names).size !== names.length) issues.push('컬럼 이름이 중복되었습니다.')
  return [...issues, ...autoIncrementIssues(dialect, spec)]
}

export function validateForeignKey(spec: ForeignKeySpec): readonly DdlIssue[] {
  const issues: DdlIssue[] = []
  if (spec.columns.length === 0 || spec.columns.every((c) => c.trim() === ''))
    issues.push('원본 컬럼을 입력하세요.')
  if (spec.refTable.trim() === '') issues.push('참조 테이블을 입력하세요.')
  if (spec.refColumns.length === 0 || spec.refColumns.every((c) => c.trim() === ''))
    issues.push('참조 컬럼을 입력하세요.')
  if (spec.columns.length !== spec.refColumns.length)
    issues.push('원본 컬럼 수와 참조 컬럼 수가 다릅니다.')
  return issues
}

function renameIssues(current: string, next: string): readonly DdlIssue[] {
  return current.trim() !== '' && current.trim() === next.trim() ? ['이름이 기존과 같습니다.'] : []
}

export function validateRenameTable(spec: RenameTableSpec): readonly DdlIssue[] {
  const issues: DdlIssue[] = []
  if (spec.table.trim() === '') issues.push('테이블을 고르세요.')
  if (spec.newName.trim() === '') issues.push('새 테이블 이름을 입력하세요.')
  else issues.push(...renameIssues(spec.table, spec.newName))
  return issues
}

export function validateRenameColumn(spec: RenameColumnSpec): readonly DdlIssue[] {
  const issues: DdlIssue[] = []
  if (spec.column.trim() === '') issues.push('바꿀 컬럼을 고르세요.')
  if (spec.newName.trim() === '') issues.push('새 컬럼 이름을 입력하세요.')
  else issues.push(...renameIssues(spec.column, spec.newName))
  return issues
}

/**
 * NOT NULL을 켜면 DEFAULT를 **요구한다** — 방언 규칙이 아니라 정책이다.
 *
 * 실측: 행이 있는 테이블에 DEFAULT 없이 NOT NULL 컬럼을 붙이면
 * sqlite와 postgres는 거부하지만 **mysql·mariadb는 성공하면서 기존 행에
 * `''`·`0`을 조용히 채운다**(STRICT_TRANS_TABLES가 켜져 있어도 그렇다).
 * 사용자는 "필수 컬럼"을 만들었다고 믿는데 기존 행은 빈 값이 된다.
 * DEFAULT를 필수로 묶으면 네 엔진이 같은 결과를 내고, 채워질 값을 사용자가 고른다.
 */
export function validateAddColumn(
  _dialect: SqlEngineId,
  spec: AddColumnSpec,
): readonly DdlIssue[] {
  const issues: DdlIssue[] = []
  if (spec.name.trim() === '') issues.push('컬럼 이름을 입력하세요.')
  if (spec.type.trim() === '') issues.push('컬럼 타입을 입력하세요.')
  const hasDefault = spec.defaultExpr !== undefined && spec.defaultExpr.trim() !== ''
  if (spec.notNull && !hasDefault)
    issues.push(
      'NOT NULL 컬럼을 추가하려면 DEFAULT가 필요합니다. 기존 행에 채울 값이 없으면 엔진이 거부하거나(sqlite·postgres) 빈 값을 조용히 채웁니다(mysql).',
    )
  return issues
}

/**
 * sqlite만 사전 검사가 필요하다(실측).
 *
 * - PK 컬럼: `cannot drop PRIMARY KEY column`
 * - 인덱스가 걸린 컬럼: `error in index … after drop column`
 *
 * postgres·mysql·mariadb는 둘 다 허용하므로 막지 않는다. 엔진이 받아 주는 것을
 * UI가 막으면 사용자는 왜 안 되는지 알 방법이 없다.
 */
export function validateDropColumn(
  dialect: SqlEngineId,
  spec: DropColumnSpec,
  facts: TableFacts,
): readonly DdlIssue[] {
  const column = spec.column.trim()
  if (column === '') return ['삭제할 컬럼을 고르세요.']
  if (dialect !== 'sqlite') return []

  const issues: DdlIssue[] = []
  const eq = (n: string) => n.trim().toLowerCase() === column.toLowerCase()
  if (facts.pkColumns.some(eq)) issues.push(`sqlite는 PK 컬럼('${column}')을 지울 수 없습니다.`)
  if (facts.indexedColumns.some(eq))
    issues.push(
      `sqlite는 인덱스가 걸린 컬럼('${column}')을 지울 수 없습니다. 먼저 그 인덱스를 삭제하세요.`,
    )
  return issues
}

export function validateDropTable(spec: DropTableSpec): readonly DdlIssue[] {
  return spec.table.trim() === '' ? ['테이블을 고르세요.'] : []
}

export function validateDropIndex(spec: DropIndexSpec): readonly DdlIssue[] {
  return spec.indexName.trim() === '' ? ['삭제할 인덱스를 고르세요.'] : []
}

export function validateIndex(spec: IndexSpec): readonly DdlIssue[] {
  const issues: DdlIssue[] = []
  if (spec.indexName.trim() === '') issues.push('인덱스 이름을 입력하세요.')
  if (spec.columns.length === 0 || spec.columns.every((c) => c.trim() === ''))
    issues.push('컬럼을 입력하세요.')
  return issues
}
