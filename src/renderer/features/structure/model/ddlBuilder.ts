import type { SqlEngineId } from '../../../../shared/types/connection'

/**
 * 방언별 DDL 문장 생성기 — 테이블 디자이너의 유일한 SQL 조립 지점.
 *
 * 순수 함수로만 구성한다: 입력 스펙 → SQL 문자열. 실행·검증·상태는 UI와
 * executor의 몫이다. 사용자는 생성된 SQL을 미리보기로 그대로 확인한 뒤
 * 기존 `operation:run`(kind: 'sql')으로 실행한다 — 새 도메인 연산을
 * 엔진마다 추가하는 대신 이미 검증된 사용자 SQL 경로를 재사용한다.
 */

export interface ColumnSpec {
  readonly name: string
  readonly type: string
  readonly notNull: boolean
  readonly primaryKey: boolean
  /** 원문 SQL 표현식(예: `0`, `'draft'`, `now()`). 비면 DEFAULT 절 생략. */
  readonly defaultExpr?: string
  /**
   * 자동 증가. 선택 필드로 두지 않는 이유는, 빠뜨려도 타입이 통과하면서
   * 조용히 "자동 증가 아님"이 되기 때문이다. 호출부가 명시하게 강제한다.
   */
  readonly autoIncrement: boolean
}

export interface CreateTableSpec {
  /** 빈 문자열·undefined면 스키마 한정 없이 테이블명만 쓴다(sqlite 등). */
  readonly schema?: string
  readonly table: string
  readonly columns: readonly ColumnSpec[]
}

export type FkAction = 'NO ACTION' | 'CASCADE' | 'SET NULL' | 'RESTRICT'

export interface ForeignKeySpec {
  readonly schema?: string
  readonly table: string
  /** 비면 CONSTRAINT 절을 생략하고 엔진이 이름을 정하게 둔다. */
  readonly constraintName?: string
  readonly columns: readonly string[]
  readonly refSchema?: string
  readonly refTable: string
  readonly refColumns: readonly string[]
  readonly onDelete?: FkAction
}

export interface IndexSpec {
  readonly schema?: string
  readonly table: string
  readonly indexName: string
  readonly columns: readonly string[]
  readonly unique: boolean
}

export interface RenameTableSpec {
  readonly schema?: string
  readonly table: string
  readonly newName: string
}

export interface RenameColumnSpec {
  readonly schema?: string
  readonly table: string
  readonly column: string
  readonly newName: string
}

/**
 * 기존 테이블에 붙일 컬럼.
 *
 * `ColumnSpec`을 재사용하지 않는다 — 그쪽의 `primaryKey`·`autoIncrement`는
 * ADD COLUMN에서 의미가 없고, 받아 두고 무시하면 사용자가 켠 설정이 조용히
 * 사라진다. 필드를 없애서 그런 상태를 만들 수 없게 한다.
 */
export interface AddColumnSpec {
  readonly schema?: string
  readonly table: string
  readonly name: string
  readonly type: string
  readonly notNull: boolean
  readonly defaultExpr?: string
}

export interface DropColumnSpec {
  readonly schema?: string
  readonly table: string
  readonly column: string
}

export interface DropTableSpec {
  readonly schema?: string
  readonly table: string
}

export interface DropIndexSpec {
  readonly schema?: string
  /** mysql 계열의 `DROP INDEX … ON <테이블>`에 필요하다. */
  readonly table: string
  readonly indexName: string
}

/**
 * 기존 테이블에서 읽어 온 사실. sqlite의 DROP COLUMN 사전 검사에만 쓴다.
 * `useTableStructure`가 이미 `describeTable`·`listIndexes`로 갖고 있는 값이다.
 */
export interface TableFacts {
  readonly pkColumns: readonly string[]
  readonly indexedColumns: readonly string[]
}

/**
 * 식별자 인용. postgres/sqlite는 큰따옴표, mysql/mariadb는 백틱.
 * 내부의 인용 문자는 두 번 적어 이스케이프한다 — 사용자가 어떤 이름을
 * 입력해도 식별자 경계를 깨고 나올 수 없게.
 */
export function quoteIdent(dialect: SqlEngineId, name: string): string {
  if (dialect === 'mysql' || dialect === 'mariadb') return '`' + name.replaceAll('`', '``') + '`'
  return '"' + name.replaceAll('"', '""') + '"'
}

function qualified(dialect: SqlEngineId, schema: string | undefined, table: string): string {
  const t = quoteIdent(dialect, table)
  return schema !== undefined && schema !== '' ? `${quoteIdent(dialect, schema)}.${t}` : t
}

/**
 * 자동 증가를 **컬럼 절**로 표현하는 방언의 조각.
 *
 * sqlite는 빈 문자열을 돌려준다 — 문법이 `AUTOINCREMENT`를 PK 절 안에서만
 * 받기 때문이다. 컬럼 절에 붙이는 형태(`"id" INTEGER PRIMARY KEY AUTOINCREMENT`)는
 * PK를 인라인으로 선언할 때만 성립하고, 이 빌더는 PK를 테이블 레벨 절로
 * 내보낸다. 테이블 레벨 PK로도 rowid 별칭이 성립하는 것은 실측으로 확인했다.
 */
function autoIncrementColumnClause(dialect: SqlEngineId): string {
  if (dialect === 'postgres') return ' GENERATED BY DEFAULT AS IDENTITY'
  if (dialect === 'mysql' || dialect === 'mariadb') return ' AUTO_INCREMENT'
  return ''
}

/**
 * PK 절에 들어갈 컬럼 조각. sqlite에서 단일 컬럼 PK가 자동 증가면
 * `AUTOINCREMENT`를 여기 붙인다.
 *
 * 복합 PK에는 붙이지 않는다 — sqlite가 문법 오류로 거부한다. 검증이 그 조합을
 * 먼저 막지만(§Task 2), 빌더가 깨진 SQL을 만들어 내지 않는 편이 안전하다.
 */
function pkColumnFragment(
  dialect: SqlEngineId,
  column: ColumnSpec,
  pkCount: number,
): string {
  const quoted = quoteIdent(dialect, column.name)
  const autoInPk = dialect === 'sqlite' && column.autoIncrement && pkCount === 1
  return autoInPk ? `${quoted} AUTOINCREMENT` : quoted
}

/** sqlite는 `ALTER TABLE … ADD CONSTRAINT`를 지원하지 않는다 — FK는 테이블 생성 시에만. */
export function supportsAddForeignKey(dialect: SqlEngineId): boolean {
  return dialect !== 'sqlite'
}

export function buildCreateTable(dialect: SqlEngineId, spec: CreateTableSpec): string {
  const lines = spec.columns.map((c) => {
    let line = `  ${quoteIdent(dialect, c.name)} ${c.type.trim()}`
    if (c.defaultExpr !== undefined && c.defaultExpr.trim() !== '')
      line += ` DEFAULT ${c.defaultExpr.trim()}`
    if (c.notNull) line += ' NOT NULL'
    if (c.autoIncrement) line += autoIncrementColumnClause(dialect)
    return line
  })
  const pk = spec.columns.filter((c) => c.primaryKey)
  if (pk.length > 0)
    lines.push(
      `  PRIMARY KEY (${pk.map((c) => pkColumnFragment(dialect, c, pk.length)).join(', ')})`,
    )
  return `CREATE TABLE ${qualified(dialect, spec.schema, spec.table)} (\n${lines.join(',\n')}\n)`
}

export function buildAddForeignKey(dialect: SqlEngineId, spec: ForeignKeySpec): string {
  if (!supportsAddForeignKey(dialect))
    throw new Error(`${dialect} does not support ALTER TABLE … ADD FOREIGN KEY`)
  const cols = spec.columns.map((c) => quoteIdent(dialect, c)).join(', ')
  const refCols = spec.refColumns.map((c) => quoteIdent(dialect, c)).join(', ')
  const constraint =
    spec.constraintName !== undefined && spec.constraintName !== ''
      ? `CONSTRAINT ${quoteIdent(dialect, spec.constraintName)} `
      : ''
  let sql =
    `ALTER TABLE ${qualified(dialect, spec.schema, spec.table)}\n` +
    `  ADD ${constraint}FOREIGN KEY (${cols})\n` +
    `  REFERENCES ${qualified(dialect, spec.refSchema, spec.refTable)} (${refCols})`
  if (spec.onDelete !== undefined && spec.onDelete !== 'NO ACTION')
    sql += `\n  ON DELETE ${spec.onDelete}`
  return sql
}

export function buildCreateIndex(dialect: SqlEngineId, spec: IndexSpec): string {
  const unique = spec.unique ? 'UNIQUE ' : ''
  // postgres/sqlite에서 인덱스명은 스키마에 귀속된다 — 이름 자체는 한정하지
  // 않고 ON 절의 테이블만 한정한다(모든 방언에서 유효한 공통형).
  const name = quoteIdent(dialect, spec.indexName)
  const cols = spec.columns.map((c) => quoteIdent(dialect, c)).join(', ')
  return `CREATE ${unique}INDEX ${name} ON ${qualified(dialect, spec.schema, spec.table)} (${cols})`
}

/**
 * 새 이름은 **비수식**으로 낸다.
 *
 * 실측: postgres에서 `ALTER TABLE s."t" RENAME TO s."t2"`는 syntax error다.
 * RENAME은 스키마를 옮기는 문장이 아니다(그건 `SET SCHEMA`). 사용자가 새 이름에
 * 점을 섞어 넣더라도 식별자 하나로 인용한다 — 인용 밖으로 새어 두 부분 이름이
 * 되는 쪽이 훨씬 나쁘다.
 *
 * **새 이름의 앞뒤 공백은 버린다.** 엔진은 `"  x  "`를 유효한 식별자로 받지만,
 * 빈 칸에 이름을 타이핑하는 사용자가 그걸 의도하는 경우는 없다. 트림하지 않으면
 * 실수로 남은 공백이 조용히 다른 이름의 테이블을 만든다. 검증도 같은 기준으로
 * 비어 있음을 판정하므로 둘이 어긋나지 않는다.
 */
export function buildRenameTable(dialect: SqlEngineId, spec: RenameTableSpec): string {
  const from = qualified(dialect, spec.schema, spec.table)
  return `ALTER TABLE ${from} RENAME TO ${quoteIdent(dialect, spec.newName.trim())}`
}

/** 네 방언 모두 같은 형태다(sqlite 3.25+, mysql 8.0+, mariadb 10.5.2+, pg). */
export function buildRenameColumn(dialect: SqlEngineId, spec: RenameColumnSpec): string {
  const t = qualified(dialect, spec.schema, spec.table)
  const from = quoteIdent(dialect, spec.column)
  const to = quoteIdent(dialect, spec.newName.trim())
  return `ALTER TABLE ${t} RENAME COLUMN ${from} TO ${to}`
}

export function buildAddColumn(dialect: SqlEngineId, spec: AddColumnSpec): string {
  let line = `${quoteIdent(dialect, spec.name)} ${spec.type.trim()}`
  // 절 순서는 CREATE TABLE과 같게 둔다 — 미리보기를 나란히 읽는 사용자가 있다.
  if (spec.defaultExpr !== undefined && spec.defaultExpr.trim() !== '')
    line += ` DEFAULT ${spec.defaultExpr.trim()}`
  if (spec.notNull) line += ' NOT NULL'
  return `ALTER TABLE ${qualified(dialect, spec.schema, spec.table)} ADD COLUMN ${line}`
}

export function buildDropColumn(dialect: SqlEngineId, spec: DropColumnSpec): string {
  const t = qualified(dialect, spec.schema, spec.table)
  return `ALTER TABLE ${t} DROP COLUMN ${quoteIdent(dialect, spec.column)}`
}

/**
 * CASCADE를 붙이지 않는다. 다른 객체를 조용히 지우는 버튼은 두지 않는다 —
 * FK가 걸려 있으면 엔진이 거부하고, 그 원문이 그대로 화면에 뜬다.
 */
export function buildDropTable(dialect: SqlEngineId, spec: DropTableSpec): string {
  return `DROP TABLE ${qualified(dialect, spec.schema, spec.table)}`
}

/**
 * 인덱스 삭제 문법은 둘로 갈린다(실측).
 *
 * - mysql·mariadb: `DROP INDEX <이름> ON <테이블>`. 표준형만 쓰면 **구문 오류**다.
 * - sqlite: 인덱스 이름만. 스키마 한정 개념이 없다.
 * - postgres: 인덱스가 스키마에 귀속된 객체이므로 **이름**을 한정하고 테이블은 쓰지 않는다.
 */
export function buildDropIndex(dialect: SqlEngineId, spec: DropIndexSpec): string {
  const name = quoteIdent(dialect, spec.indexName)
  if (dialect === 'mysql' || dialect === 'mariadb')
    return `DROP INDEX ${name} ON ${qualified(dialect, spec.schema, spec.table)}`
  if (dialect === 'sqlite') return `DROP INDEX ${name}`
  return `DROP INDEX ${qualified(dialect, spec.schema, spec.indexName)}`
}

